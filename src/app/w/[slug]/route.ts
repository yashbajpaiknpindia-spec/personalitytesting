// Analytics tracker: fires on page load, sends duration on exit.
// Uses sendBeacon so exit events survive mobile tab switches.
// No cookies, no external calls — fully first-party.
function bsTrackerScript(siteId: string): string {
  return `<script>
(function(){
  try{
    var sid=sessionStorage.getItem('_bss')||(Math.random().toString(36).slice(2)+Math.random().toString(36).slice(2));
    sessionStorage.setItem('_bss',sid);
    var ep='/api/website/${siteId}/track';
    var t0=Date.now();
    function send(dur){
      var b=JSON.stringify({sessionId:sid,durationMs:dur||undefined});
      if(navigator.sendBeacon){navigator.sendBeacon(ep,new Blob([b],{type:'application/json'}));}
      else{var x=new XMLHttpRequest();x.open('POST',ep,false);x.setRequestHeader('Content-Type','application/json');try{x.send(b);}catch(e){}}
    }
    send(null);
    var sent=false;
    function onExit(){if(sent)return;sent=true;send(Date.now()-t0);}
    document.addEventListener('visibilitychange',function(){if(document.visibilityState==='hidden')onExit();});
    window.addEventListener('pagehide',onExit);
  }catch(e){}
})();
</script>`
}

