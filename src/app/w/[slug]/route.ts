// Guard: returns true only if the body has real page content (>100 chars after stripping scripts).
// Catches the old max_tokens truncation bug where Claude wrote <head> meta but never reached <body>.
function hasBodyContent(html: string): boolean {
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)
  if (!bodyMatch) return false
  const bodyText = bodyMatch[1]
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/<script[\s\S]*?<\/script>/gi, '')
    .trim()
  return bodyText.length > 100
}

export async function GET(
  _req: Request,
  { params }: { params: { slug: string } }
) {
  const site = await db.userWebsite.findUnique({
    where: { slug: params.slug },
    select: { id: true, htmlContent: true, isPublished: true, name: true, slug: true },
  }).catch(() => null)

  if (!site) {
    return new Response(NOT_FOUND_HTML, {
      status: 404,
      headers: { 'Content-Type': 'text/html; charset=utf-8' },
    })
  }

  if (!site.isPublished) {
    return new Response(NOT_PUBLISHED_HTML(site.name ?? 'Website'), {
      status: 200,
      headers: { 'Content-Type': 'text/html; charset=utf-8' },
    })
  }

  const rawHtml = site.htmlContent?.trim() ?? ''

  // ── Guard: empty body → show regenerate prompt instead of blank page ────────
  // This catches sites where Claude was cut off mid-generation (max_tokens) before
  // writing any <body> content. The stored HTML has a <head> with meta tags but
  // nothing visible. Serving it would show a blank white/dark page with no indication
  // of what went wrong. We show a clear "regenerate" message instead.
  if (!rawHtml || !hasBodyContent(rawHtml)) {
    console.warn(`[w/${params.slug}] Site ${site.id} has empty body content — serving truncation page`)
    return new Response(TRUNCATED_HTML(site.slug ?? params.slug), {
      status: 200,
      headers: {
        'Content-Type': 'text/html; charset=utf-8',
        'Cache-Control': 'no-store',
      },
    })
  }

  // Inject all scripts before </body>:
  // 0. VISIBILITY_FIX_STYLE  — fixes legacy opacity:0/IntersectionObserver hidden content
  // 0b. RESPONSIVE_FIX_STYLE — runtime responsive compat for old fixed-width sites
  // 1. HEIGHT_SYNC_SCRIPT    — iframe resize for the generate page preview
  // 2. bsTrackerScript       — first-party analytics (no cookies, no external requests)
  // 3. bsBackendScript       — form capture + blog rendering
  const inject = `${MOBILE_NAV_SCRIPT}${IMAGE_FIX_SCRIPT}${bsTrackerScript(site.id)}${bsBackendScript(site.id)}`

  // Inject visibility fix + responsive compat into <head> and other scripts before </body>
  let html = repairCommonGeneratedHtmlIssues(stripTemplateLanguage(rawHtml))
    .replace(/<style[^>]+id=["']bs-mobile-root-hero-fix-v[67]["'][\s\S]*?<\/style>/gi, '')
  if (html.includes('</head>')) {
    html = html.replace('</head>', VISIBILITY_FIX_STYLE + RESPONSIVE_FIX_STYLE + EXISTING_WEBSITE_SPACE_FIX_STYLE + MOBILE_ROOT_HERO_FIX_STYLE + EXISTING_WEBSITE_LAYOUT_FIX_SCRIPT + '\n</head>')
  } else {
    // No head tag — prepend at top
    html = VISIBILITY_FIX_STYLE + RESPONSIVE_FIX_STYLE + EXISTING_WEBSITE_SPACE_FIX_STYLE + MOBILE_ROOT_HERO_FIX_STYLE + EXISTING_WEBSITE_LAYOUT_FIX_SCRIPT + '\n' + html
  }
  html = html.replace(/<\/body>/i, `${inject}</body>`)

  return new Response(html, {
    status: 200,
    headers: {
      'Content-Type':  'text/html; charset=utf-8',
      'X-Frame-Options': 'SAMEORIGIN',
      'Cache-Control': 'no-store',
    },
  })
}
