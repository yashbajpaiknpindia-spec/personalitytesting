function replaceDeprecatedTemplateImages(html: string): string {
  return html.replace(/https:\/\/source\.unsplash\.com\/featured\/(?:\d+x\d+\/)?\?([^"'\s<)]+)/gi, (_match, query: string) => stableTemplateImageForQuery(query))
}

function repairCommonTemplateHtmlIssues(html: string): string {
  return replaceDeprecatedTemplateImages(html)
    // Some imported sample templates had <img ... /> loading="lazy" which can break parsing in browsers.
    .replace(/<img([^>]*?)\/\s+(loading|decoding|style|class|alt|src)=/gi, '<img$1 $2=')
    .replace(/<img([^>]*?)\/\s*>/gi, '<img$1>')
    // Prevent accidental 100vw + scrollbar overflow on generated sites.
    .replace(/width:\s*100vw/gi, 'width:100%')
    .replace(/min-width:\s*100vw/gi, 'min-width:100%')
}

function replaceTextOutsideTags(html: string, replacements: Array<[RegExp, string]>): string {
  return html
    .split(/(<[^>]+>)/g)
    .map(part => {
      if (part.startsWith('<')) return part
      let clean = part
      for (const [pattern, replacement] of replacements) clean = clean.replace(pattern, replacement)
      return clean.replace(/\s{2,}/g, ' ')
    })
    .join('')
}

function replaceFirstTextInTag(html: string, tag: string, value: string): string {
  const pattern = new RegExp(`(<${tag}\\b[^>]*>)[\\s\\S]*?(<\\/${tag}>)`, 'i')
  return html.replace(pattern, `$1${safeText(value)}$2`)
}

function replaceNthTextInTags(html: string, tag: string, values: string[], offset = 0): string {
  let index = 0
  return html.replace(new RegExp(`(<${tag}\\b[^>]*>)[\\s\\S]*?(<\\/${tag}>)`, 'gi'), (match, open, close) => {
    const value = values[index - offset]
    index += 1
    if (index <= offset || value === undefined) return match
    return `${open}${safeText(value)}${close}`
  })
}

