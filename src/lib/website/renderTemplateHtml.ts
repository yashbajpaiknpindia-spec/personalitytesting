// Convert #rrggbb to "r,g,b" for rgba()
function hexToRgb(hex: string): string {
  const clean = hex.replace('#', '')
  const r = parseInt(clean.slice(0, 2), 16)
  const g = parseInt(clean.slice(2, 4), 16)
  const b = parseInt(clean.slice(4, 6), 16)
  if (isNaN(r) || isNaN(g) || isNaN(b)) return '0,0,0'
  return `${r},${g},${b}`
}

// ── HTML completeness repair ──────────────────────────────────────────────────

export function ensureTemplateHtmlComplete(html: string): string {
  let fixed = html.trim()
  if (!fixed) return fixed

  if (!fixed.toLowerCase().startsWith('<!doctype')) {
    fixed = `<!DOCTYPE html>\n<html lang="en">\n<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"></head>\n<body>\n${fixed}\n</body>\n</html>`
    return fixed
  }
  if (!/<html/i.test(fixed))  fixed = `<!DOCTYPE html>\n<html lang="en">\n${fixed}\n</html>`
  if (!/<head/i.test(fixed))  fixed = fixed.replace(/<html[^>]*>/i, m => `${m}\n<head></head>`)
  if (!/<body/i.test(fixed))  fixed = fixed.replace(/<\/head>/i, '</head>\n<body>') + '\n</body>'
  if (!/<\/html>/i.test(fixed)) fixed += '\n</html>'

  return fixed
}

// ── Safe string replacement helpers ──────────────────────────────────────────

function replaceFirst(html: string, pattern: RegExp, replacement: string): string {
  return html.replace(pattern, replacement)
}

function escapeHtml(str: string): string {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
}

function safeText(str: string): string {
  // Allow normal HTML in the template, but escape values coming from user input
  return str.replace(/[<>"]/g, c => ({ '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c] ?? c))
}


