function hasThinTemplateContent(html: string): boolean {
  const bodyMatch = html.match(/<body[^>]*>([\s\S]*?)<\/body>/i)
  const body = bodyMatch ? bodyMatch[1] : html
  const text = body
    .replace(/<script[\s\S]*?<\/script>/gi, ' ')
    .replace(/<style[\s\S]*?<\/style>/gi, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase()

  const placeholderHits = [
    'service one', 'service two', 'service three', 'template is intentionally',
    'structure is intentionally predictable', 'your backend can safely replace',
    'lorem ipsum', 'feature one', 'feature two', 'placeholder'
  ].filter(token => text.includes(token)).length

  const sectionCount = (html.match(/<section\b/gi) || []).length
  return placeholderHits > 0 || text.length < 1200 || sectionCount < 3
}

function injectBeforeFooterOrBody(html: string, block: string): string {
  if (html.includes('id="bs-ready-content"') || html.includes("id='bs-ready-content'")) return html
  if (/<footer\b/i.test(html)) return html.replace(/<footer\b/i, `${block}\n<footer`)
  if (/<\/body>/i.test(html)) return html.replace(/<\/body>/i, `${block}\n</body>`)
  return html + block
}

